    private static let parsed: [Character: [(row: Int, col: Int)]] = glyphs.mapValues { lines in
        lines.enumerated().flatMap { row, line in
            line.enumerated().compactMap { col, c in c == "#" ? (row, col) : nil }
        }
    }

