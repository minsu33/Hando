// 5x7 비트맵. 없는 글자는 '?'로
enum PixelFont {
    static let columns = 5
    static let rows = 7
    static let spacing = 1

    static func dots(for char: Character) -> [(row: Int, col: Int)] {
        let key = Character(char.uppercased())
        return parsed[key] ?? parsed["?"] ?? []
    }

